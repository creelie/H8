def fig_chernline():
    """The Weil line as a plane, the orbit inside it, the transverse axis."""
    cam = Camera(eye=(7.0, -7.6, 4.4), target=(0, 0, 0.15), focal=8.6,
                 scale=2.35)
    sc, P = Scene(cam), Placer()

    sc.surface(lambda u, v: (1.65 * u, 1.65 * v, 0.0), (-1, 1), (-1, 1),
               22, 22, base="PIndigo", opacity=0.32, ambient=0.54,
               diffuse=0.42)

    # the orbit of K^x on the plane: tau^{2n} acting as a rotation-scaling
    sc.curve(lambda t: (1.18 * math.exp(0.10 * t) * math.cos(t),
                        1.18 * math.exp(0.10 * t) * math.sin(t), 0.0),
             (-2.6, 1.05), 200, "PMag,line width=1.15pt", chunk=2)
    for t in (-2.2, -1.1, 0.0, 0.9):
        r = 1.18 * math.exp(0.10 * t)
        sc.dot3((r * math.cos(t), r * math.sin(t), 0.0),
                "circle,fill=PMag,draw=white,line width=0.5pt,inner sep=1.9pt",
                priority=4)

    sc.polyline([(0, 0, -1.30), (0, 0, 1.55)],
                "PAmber,line width=1.15pt,-{Stealth[length=4pt]}")
    sc.dot3((0, 0, 0.95),
            "circle,fill=PAmber,draw=white,line width=0.5pt,inner sep=1.9pt",
            priority=4)
    sc.dot3((0, 0, 0), "circle,fill=PInk,inner sep=1.4pt,draw=none",
            priority=4)

    P.add((1.65, 1.10, 0.0), r"$W(A)$, a plane", "text=PIndigo", side="R")
    P.add((1.30, -0.35, 0.0), r"the $\Kx$-orbit: $\tau^{2n}$", "text=PMag",
          side="R")
    P.add((0, 0, 1.30), r"$\QQ\eta^{n}$, the norm character", "text=PAmber",
          side="R")
    P.add((-1.20, -1.10, 0.0), r"no $\Kx$-stable line inside $W(A)$",
          "text=PSlate", side="L")
    write("fig_chernline",
          "The Weil line is a plane and the orbit of K^x spans it; eta^n "
          "sits on a transverse axis with a different character.",
          sc, P)


