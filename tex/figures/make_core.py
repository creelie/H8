def fig_annihilator():
    """H^{0,2} in three blocks, the middle one carried to zero."""
    cam = Camera(eye=(8.0, -8.4, 4.8), target=(0.55, 0.0, 0.42), focal=8.8,
                 scale=2.25)
    sc, P = Scene(cam), Placer()

    n = 3
    blocks = [(binom(n, 2), "PIndigo", r"\bigwedge^{2}V_{+}^{0,1}"),
              (n * n, "PAmber", r"V_{+}^{0,1}\otimes V_{-}^{0,1}"),
              (binom(n, 2), "PMag", r"\bigwedge^{2}V_{-}^{0,1}")]
    z = 0.0
    tops = []
    for d, col, lab in blocks:
        h = 0.20 + 0.105 * d
        box(sc, 0.0, 0.0, z, 0.92, 0.72, h, col, op=0.88)
        tops.append((z + h / 2, d, col, lab))
        z += h + 0.085

    # the image side: the two outer blocks survive, the middle goes to zero
    sc.polyline([(1.15, 0.36, tops[0][0]), (2.15, 0.36, tops[0][0])],
                "PIndigo,line width=0.9pt,-{Stealth[length=4pt]}")
    sc.polyline([(1.15, 0.36, tops[2][0]), (2.15, 0.36, tops[2][0])],
                "PMag,line width=0.9pt,-{Stealth[length=4pt]}")
    sc.polyline([(1.15, 0.36, tops[1][0]), (2.15, 0.36, tops[1][0])],
                "PAmber,line width=0.9pt,-{Stealth[length=4pt]}")
    box(sc, 2.25, 0.10, tops[0][0] - 0.16, 0.42, 0.52, 0.32, "PIndigo",
        op=0.88)
    box(sc, 2.25, 0.10, tops[2][0] - 0.16, 0.42, 0.52, 0.32, "PMag", op=0.88)
    sc.dot3((2.46, 0.36, tops[1][0]),
            "circle,fill=PAmber,draw=white,line width=0.5pt,inner sep=2.2pt",
            priority=4)

    P.add((0.46, 0.36, tops[0][0]), r"$\binom{n}{2}=3$", "text=PIndigo",
          side="L")
    P.add((0.46, 0.36, tops[1][0]), r"$n^{2}=9$, the mixed block",
          "text=PAmber", side="L")
    P.add((0.46, 0.36, tops[2][0]), r"$\binom{n}{2}=3$", "text=PMag",
          side="L")
    P.add((2.46, 0.36, tops[1][0]), r"$0$", "text=PAmber", side="R")
    P.add((2.46, 0.36, tops[0][0]), r"injective", "text=PIndigo", side="R")
    P.add((1.65, 0.36, tops[2][0] + 0.55), r"$z\mapsto z\cdot\omega$",
          "text=PSlate", side="R")
    write("fig_annihilator",
          "H^{0,2} in three blocks at n = 3: the outer two are carried "
          "injectively, the middle one of dimension n^2 goes to zero.",
          sc, P)


