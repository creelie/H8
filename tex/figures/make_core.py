def fig_chernline():
    """The Weil line as the plane of omega_1, omega_2 at n = 2, K = Q(sqrt-2),
    the orbit of omega_1 under the powers of tau = 1 + sqrt(-2)/4, and the
    axis of eta^2 with the orbit of eta^2."""
    d = 2
    # tau^4 = 17/64 + (7/8) sqrt(-2) acts on (a, b), a omega_1 + b omega_2,
    # by the rational matrix [[17/64, -7/8], [7/4, 17/64]]
    al, be = 17 / 64, 7 / 8
    rho = math.hypot(al, be * math.sqrt(d))           # |tau^4| = Nm(tau)^2
    th = math.atan2(be * math.sqrt(d), al)             # arg tau^4

    def orbit(t):
        """omega_1 moved by tau^{4t}, in the coordinates (a, b)."""
        r = rho ** t
        return (r * math.cos(t * th), math.sqrt(d) * r * math.sin(t * th), 0.0)

    cam = orbit_cam((0.0, 0.0, 0.6), 34, 22, R=36)
    F = Fig("fig_chernline",
            "The Weil line W(A) at n = 2, K = Q(sqrt-2), as the plane of "
            "omega_1, omega_2, with the orbit of omega_1 under tau = "
            "1 + sqrt(-2)/4 and the axis Q eta^2 with the orbit of eta^2.",
            cam)
    A, B = 2.0, 2.4                                     # the half sides
