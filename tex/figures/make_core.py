def fig_weilcube():
    """The Boolean lattice of subsets of {1,2,3,4}, the 4-cube projected with
    height |T|, the vertices coloured by the parity of |T|."""
    # horizontal parts of the four edge directions: centred, and chosen so
    # that the six sets of size two form a regular hexagon
    V = [(0.5, math.sqrt(3) / 2), (0.5, -math.sqrt(3) / 2), (0.0, 0.0),
         (-1.0, 0.0)]
    H = 0.60

    def pos(T):
        return (sum(V[i][0] for i in range(4) if T >> i & 1),
                sum(V[i][1] for i in range(4) if T >> i & 1),
                H * bin(T).count("1"))

    cam = orbit_cam((0.0, 0.0, 2 * H), -6, 10, R=30)
    F = Fig("fig_weilcube",
            "The 2^{2n} = 16 monomials w(T) at n = 2 as the vertices of the "
            "4-cube, projected with height |T|; the parity of |T| separates "
            "omega_1 from omega_2.", cam)
    fit(cam, [pos(T) for T in range(16)], 5.0)

    # the zonotope: its twelve faces, to shade them and to tell front edges
    # from hidden ones
    G = [(V[i][0], V[i][1], H) for i in range(4)]
    faces = []
    for i, j in itertools.combinations(range(4), 2):
        n = cross(G[i], G[j])
        for sgn in (1, -1):
            m = smul(sgn, n)
            S = [k for k in range(4) if k not in (i, j) and dot(G[k], m) > 0]
            base = (0.0, 0.0, 0.0)
            for k in S:
                base = addv(base, G[k])
            quad = [base, addv(base, G[i]), addv(addv(base, G[i]), G[j]),
                    addv(base, G[j])]
            faces.append((m, dot(base, m), quad))

    def visible(p):
        for n, c, _ in faces:
            if abs(dot(p, n) - c) < 1e-9 and dot(n, sub(cam.eye, p)) > 0:
                return True
        return False

    for n, c, quad in faces:
        cen = smul(0.25, (sum(q[0] for q in quad), sum(q[1] for q in quad),
                          sum(q[2] for q in quad)))
        front = dot(n, sub(cam.eye, cen)) > 0
        F.poly3(quad, fill=F.tone(n, "PSlate", lo=6, hi=22), opacity=0.55,
                prio=-1, depth=F.D(cen) + (0 if front else 0.5))

    # the level sets |T| = 1, 2, 3 as dotted rings through their vertices
    for k in (1, 2, 3):
        on = [pos(T) for T in range(16) if bin(T).count("1") == k]
        ring = [p for p in on if abs(p[0]) + abs(p[1]) > 1e-9]
        ring.sort(key=lambda p: math.atan2(p[1], p[0]))
        col = "PIndigo" if k % 2 == 0 else "PMag"
        for p, q in zip(ring, ring[1:] + ring[:1]):
            F.line3([p, q], "%s!55,line width=0.5pt,dash pattern=on 0.6pt "
                            "off 1.4pt" % col, prio=0)

    # the 32 edges, front ones solid and hidden ones dashed
    for a in range(16):
        for i in range(4):
            b = a | (1 << i)
            if b == a:
                continue
            pa, pb = pos(a), pos(b)
            mid = smul(0.5, addv(pa, pb))
            if visible(mid):
                F.line3([pa, pb], "PSlate!90!black,line width=0.62pt", prio=1)
            else:
                F.line3([pa, pb], "PSlate!70,line width=0.45pt,"
                                  "dash pattern=on 1.6pt off 1.3pt", prio=1)
    # the sixteen vertices, over everything
    for T in range(16):
        even = bin(T).count("1") % 2 == 0
        F.dot3(pos(T), "PIndigo" if even else "PMag", r=2.3, prio=4,
               depth=-1e5 + F.D(pos(T)))

    # on the right, for each level: |T|, the number of monomials, the class
    # they belong to and their common coefficient, each row at the height of
    # the centre of its level
    coef = [r"$d^{2}$", r"$d$", r"$-d$", r"$-1$", r"$1$"]
    who = [r"$\omega_{1}$", r"$\omega_{2}$", r"$\omega_{1}$", r"$\omega_{2}$",
           r"$\omega_{1}$"]
    xr = max(F.P(pos(T))[0] for T in range(16)) + 0.75
    cols = (0.0, 1.10, 2.25, 3.60)
    for k in range(5):
        col = "PIndigo" if k % 2 == 0 else "PMag"
        y = F.P((0.0, 0.0, k * H))[1]
        F.label(xr + cols[0], y, "$%d$" % k)
        F.label(xr + cols[1], y, "$%d$" % binom(4, k))
        F.label(xr + cols[2], y, who[k], color=col)
        F.label(xr + cols[3], y, coef[k], color=col)
    ytop = F.P((0.0, 0.0, 4 * H))[1] + 0.62
    for c, t in zip(cols, (r"$\lvert T\rvert$", "terms", "class",
                           "coefficient")):
        F.label(xr + c, ytop, t, font=r"\footnotesize" if "$" not in t else None)
    F.flat("  \\draw[PRule,line width=0.4pt] (%s,%s) -- (%s,%s);\n"
           % (f4(xr - 0.40), f4(ytop - 0.30), f4(xr + cols[3] + 0.75),
              f4(ytop - 0.30)))
    F.flat("  \\draw[PRule,line width=0.4pt] (%s,%s) -- (%s,%s);\n"
           % (f4(xr + 0.40), f4(ytop + 0.25),
              f4(xr + 0.40), f4(F.P((0, 0, 0))[1] - 0.30)))

    # the two extreme monomials
    q = F.P(pos(0))
    F.label(q[0], q[1] - 0.28, r"$w(\emptyset)=x_{1}x_{2}x_{3}x_{4}$",
            anchor="north", color="PIndigo")
    q = F.P(pos(15))
    F.label(q[0], q[1] + 0.28, r"$w(\{1,2,3,4\})=y_{1}y_{2}y_{3}y_{4}$",
            anchor="south", color="PIndigo")
    # one edge named: T and T + {4} differ by the substitution x_4 -> y_4
    m = F.P(smul(0.5, addv(pos(0), pos(8))))
    lx, ly = m[0] - 1.05, m[1] - 0.55
    F.label(lx, ly, r"$x_{4}\mapsto y_{4}$", anchor="east", color="PSlate")
    F.leader((lx + 0.04, ly), m, free=0.04)
    F.write()


