#!/usr/bin/env python3
"""
make_core.py

The figures of the sections on the explicit Weil classes, the character
grading, the divisor obstruction and the annihilator, each drawn from the
data the paper computes.

  fig_weilcube      the 2^{2n} monomials w(T) at n = 2 as the Boolean lattice
                    of subsets of {1,2,3,4}, projected from the 4-cube with the
                    height equal to |T|; the parity of |T| separates the eight
                    monomials of omega_1 from the eight of omega_2, and each
                    level carries the one coefficient of eq:n2omega1-2
  fig_hodgespike    dim Hdg^k(A) over k and n = 2, 3, 4 (thm:hdgcount): one
                    class eta^k in every degree, and the two dimensions of the
                    Weil line stacked on it at k = n
  fig_charactergrid the K^x-grading of H^*(A,C) at n = 3 on the grid of pairs
                    (r,s), with the summands of H^{2n} raised to their true
                    dimensions C(6,r)C(6,6-r); the Weil line at the two ends of
                    the antidiagonal, eta^n in the middle, on the diagonal of
                    the norm characters
  fig_chernline     the Weil line W(A) as the plane of omega_1, omega_2 at
                    n = 2, K = Q(sqrt(-2)), with the orbit of omega_1 under the
                    powers of tau = 1 + sqrt(-2)/4, acting through the rational
                    matrix of tau^4, and the transverse axis Q eta^n with the
                    orbit of eta^n, on which tau acts through Nm(tau)^n
  fig_annihilator   the fifteen basis vectors of H^{0,2} = wedge^2 H^{0,1} at
                    n = 3, as the cells above the diagonal of a 6 x 6 grid,
                    with the six whose product with omega is nonzero standing
                    and the nine mixed products of the kernel flat
  fig_witness       the values c(tau)^n = (tau/conj tau)^n, n = 0..12, on the
                    unit circle for bad and good witnesses at d = 1 and d = 3,
                    stacked over n as a helix; the characters tau^{2n} and
                    Nm^n agree at tau exactly where the helix meets the line
                    c^n = 1 (lem:charsdiffer, rem:witness)

Every label is written as  \\node[lbl,...] at (x,y) {...};  so that
checkfigs.py can read it back.  In addition each figure is audited against its
own raster before it is written: the exact box of every label is read from
TeX, the drawing without its labels is rasterised, and a label is rejected if
any ink lies under it, if it meets another label, or if a leader line crosses
ink, another label or another leader.
"""
