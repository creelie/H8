#!/usr/bin/env python3
"""
make_core.py

Figures 1 to 5, rebuilt in three dimensions from their own data.  Nothing
here is drawn by eye: the tesseract is the real 4-cube projected, the bar
heights are the dimensions the paper computes, and the orbit is the actual
image of K^x acting by tau^{2n}.  Shading is Lambert, the draw order is by
depth, and labels are placed outside the ink by place.py with leaders, so no
label can touch the drawing or another label.

  fig_weilcube      the 2^{2n} monomials w(T) as the vertices of the 4-cube,
                    projected, with the bipartition by |T| mod 2 that splits
                    the Weil line into its two generators
  fig_hodgespike    dim Hdg^k(A) over the two axes k and n, as a solid bar
                    field: one everywhere except the middle degree, three there
  fig_charactergrid the K^x-grading of H^{2n}, the summand at (r,s) having
                    dimension C(2n,r)C(2n,s), with the two cells that carry the
                    Weil line and the one that carries eta^n marked
  fig_chernline     the Weil line as a plane, the orbit of K^x inside it, and
                    the transverse axis carrying eta^n
  fig_annihilator   H^{0,2} in its three blocks, of dimensions C(n,2), n^2 and
                    C(n,2), with the middle one carried to zero by the class
"""
import math
import os
import sys
from itertools import combinations

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from render3d import Camera, Scene, addv, smul, sub, unit, cross
from place import Placer

HEAD = r"""%% {name}.tex   (generated by make_core.py; do not edit by hand)
%% {blurb}
\documentclass[tikz,border=8pt]{{standalone}}
\usepackage{{amsmath,amssymb}}
\usetikzlibrary{{arrows.meta,calc}}
\input{{palette}}
\begin{{document}}
\begin{{tikzpicture}}[x=1cm,y=1cm,line join=round,line cap=round,
  font=\small,text=PInk]
"""
TAIL = "\\end{tikzpicture}\n\\end{document}\n"


def write(name, blurb, sc, P):
    body = sc.emit()
    bad = P.check(body, sc.cam)
    if bad:
        raise SystemExit("placement failure in %s: %s" % (name, bad))
    labels = P.emit(body, sc.cam)
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, name + ".tex"), "w") as f:
        f.write(HEAD.format(name=name, blurb=blurb))
        f.write(body)
        f.write(labels)
        f.write(TAIL)
    print("%-18s %2d labels, clear of the ink and of each other"
          % (name, len(P.items)))


def binom(n, k):
    if k < 0 or k > n:
        return 0
    r = 1
    for i in range(k):
        r = r * (n - i) // (i + 1)
    return r


def box(sc, x0, y0, z0, dx, dy, dz, base, op=0.86, edge=True):
    """An axis-aligned solid, six faces, depth sorted by the renderer."""
    faces = [
        (lambda u, v: (x0 + dx * u, y0 + dy * v, z0)),
        (lambda u, v: (x0 + dx * u, y0 + dy * v, z0 + dz)),
        (lambda u, v: (x0, y0 + dy * u, z0 + dz * v)),
        (lambda u, v: (x0 + dx, y0 + dy * u, z0 + dz * v)),
        (lambda u, v: (x0 + dx * u, y0, z0 + dz * v)),
        (lambda u, v: (x0 + dx * u, y0 + dy, z0 + dz * v)),
    ]
    for f in faces:
        sc.surface(f, (0, 1), (0, 1), 1, 1, base=base, opacity=op,
                   ambient=0.42, diffuse=0.54, edge=edge)


