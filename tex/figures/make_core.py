def fig_weilcube():
    """The 4-cube, projected, coloured by the parity of |T|."""
    cam = Camera(eye=(7.2, -7.8, 4.6), target=(0, 0, 0.0), focal=8.6,
                 scale=2.05)
    sc, P = Scene(cam), Placer()

    # a standard projection of {0,1}^4 into R^3: the fourth axis goes to a
    # short diagonal, which is what makes the two cubes visibly nested
    E = [(1.55, 0.0, 0.0), (0.0, 1.55, 0.0), (0.0, 0.0, 1.55),
         (0.62, 0.62, 0.58)]

    def pt(T):
        p = (0.0, 0.0, 0.0)
        for i in range(4):
            if T & (1 << i):
                p = addv(p, E[i])
        return addv(p, (-1.08, -1.08, -1.06))

    for a in range(16):
        for i in range(4):
            b = a | (1 << i)
            if b != a:
                even = bin(a).count("1") % 2 == 0
                sc.polyline([pt(a), pt(b)],
                            "%s,line width=0.55pt,opacity=0.55"
                            % ("PIndigo" if even else "PMag"))
    for a in range(16):
        even = bin(a).count("1") % 2 == 0
        sc.dot3(pt(a),
                "circle,fill=%s,draw=white,line width=0.55pt,inner sep=2.1pt"
                % ("PIndigo" if even else "PMag"), priority=4)

    P.add(pt(0), r"$T=\emptyset$", "text=PIndigo", side="L")
    P.add(pt(15), r"$T=\{1,2,3,4\}$", "text=PIndigo", side="R")
    P.add(pt(1), r"$|T|$ odd: $\omega_{2}$", "text=PMag", side="L")
    P.add(pt(3), r"$|T|$ even: $\omega_{1}$", "text=PIndigo", side="R")
    P.add(pt(7), r"$2^{2n}=16$ monomials $w(T)$", "text=PSlate", side="R")
    write("fig_weilcube",
          "The 4-cube of monomials w(T), with the bipartition by the parity "
          "of |T| that separates the two generators of the Weil line.",
          sc, P)


