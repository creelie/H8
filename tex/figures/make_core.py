# =============================================================== annihilator
def fig_annihilator():
    """H^{0,2} = wedge^2 H^{0,1} at n = 3: the fifteen products e_i ^ e_j,
    i < j, of the basis u_1, u_2, u_3 of V_+^{0,1} and v_1, v_2, v_3 of
    V_-^{0,1}, over the 6 x 6 grid; the six whose product with omega is
    nonzero are raised, the nine mixed ones, the kernel, lie flat."""
    n = 3
    N = 2 * n
    names = [r"$u_{%d}$" % (k + 1) for k in range(n)] + \
            [r"$v_{%d}$" % (k + 1) for k in range(n)]
    cam = orbit_cam((N / 2, -N / 2, 0.0), -20, 46, R=40)
    F = Fig("fig_annihilator",
            "H^{0,2} at n = 3 as the cells i < j of a 6 x 6 grid: the six "
            "products carried injectively by z -> z.omega are raised, the "
            "n^2 = 9 mixed products of the kernel lie flat.", cam)
    HR = 0.42                                   # the height of a raised cell

    def cell(i, j):
        """the centre of cell (row i, column j), 0-based"""
        return (j + 0.5, -(i + 0.5))

    g0, g1 = 0.0, float(N)
    floor = [(g0, -g1, 0), (g1, -g1, 0), (g1, -g0, 0), (g0, -g0, 0)]
    fit(cam, floor, 9.9)

    # the floor: the upper triangle tinted, the lower one left white
    F.poly3(floor, fill="white", draw="PRule", lw=0.45, depth=1e6, prio=-7)
    up = [(g0, -g0, 0), (g1, -g0, 0), (g1, -g1, 0)]
    stair = [(g0, -g0, 0)]
    for k in range(N):
        stair += [(k + 1.0, -(k + 0.0), 0), (k + 1.0, -(k + 1.0), 0)]
    F.poly3(stair + [(g1, -g1, 0), (g1, -g0, 0)], fill="WSlate", depth=1e6,
            prio=-6)
    for k in range(1, N):
        w = "0.6pt" if k == n else "0.22pt"
        c = "PSlate!80" if k == n else "PRule!85"
        F.line3([(k, -g0, 0), (k, -g1, 0)], "%s,line width=%s" % (c, w),
                prio=-5, depth=1e6)
        F.line3([(g0, -k, 0), (g1, -k, 0)], "%s,line width=%s" % (c, w),
                prio=-5, depth=1e6)
    # the diagonal i = j, where e ^ e = 0, crossed out
    for i in range(N):
        x, y = cell(i, i)
        for sgn in (1, -1):
            F.line3([(x - 0.2, y - 0.2 * sgn, 0), (x + 0.2, y + 0.2 * sgn, 0)],
                    "PSlate!70,line width=0.45pt", prio=-4, depth=1e6)
    # the fifteen cells i < j
    W = 0.70
    for i in range(N):
        for j in range(i + 1, N):
            x, y = cell(i, j)
            if j < n:
                col, h = "PIndigo", HR
            elif i >= n:
                col, h = "PMag", HR
            else:
                col, h = "PAmber", 0.04
            F.prism((x - W / 2, y - W / 2, 0), (x + W / 2, y + W / 2, h), col)

    # the basis along the back edge (columns) and the left edge (rows)
    cen = F.P((N / 2, -N / 2, 0))
    F.edge_ticks((g0, -g1, 0), (g1, -g1, 0), [(k + 0.5) / N for k in range(N)],
                 names, (cen[0], cen[1] - 50), font=None, gap=0.10)
    F.edge_ticks((g0, -g0, 0), (g0, -g1, 0), [(k + 0.5) / N for k in range(N)],
                 names, (cen[0] - 50, cen[1]), font=None, gap=0.10)

    # the three blocks and what z -> z.omega does to each
    def centre(cells, z):
        xs = [cell(i, j)[0] for i, j in cells]
        ys = [cell(i, j)[1] for i, j in cells]
        return (sum(xs) / len(xs), sum(ys) / len(ys), z)
    pp = [(0, 1), (0, 2), (1, 2)]
    mm = [(3, 4), (3, 5), (4, 5)]
    pm = [(i, j) for i in range(n) for j in range(n, N)]
    ml = "align=left"
    F.alabel(F.P(centre([(0, 1)], HR)),
             r"$\bigwedge^{2}V_{+}^{0,1}$, $\binom{n}{2}=3$\\"
             r"$z\mapsto b\,z\wedge\alpha_{-}\neq0$",
             color="PIndigo", prefer=110, spread=60, rmin=0.8, rmax=4.0,
             free=0.45)
    F.alabel(F.P(centre([(0, 5)], 0.04)),
             r"$V_{+}^{0,1}\otimes V_{-}^{0,1}$, $n^{2}=9$\\"
             r"$u\wedge v\mapsto 0$",
             color="PAmber", prefer=30, spread=60, rmin=0.8, rmax=4.0,
             free=0.40)
    F.alabel(F.P(centre([(4, 5)], HR)),
             r"$\bigwedge^{2}V_{-}^{0,1}$, $\binom{n}{2}=3$\\"
             r"$z\mapsto a\,z\wedge\alpha_{+}\neq0$",
             color="PMag", prefer=-10, spread=60, rmin=0.8, rmax=4.0,
             free=0.45)
    for i in F.labels[-3:]:
        i["extra"] = ml
    q = F.P((g1, -g1, 0))
    F.label(q[0] + 0.25, q[1] - 0.05,
            r"$\omega=a\,\alpha_{+}+b\,\alpha_{-}$, $ab\neq0$",
            anchor="west")
    F.write()


