def fig_hodgespike():
    """dim Hdg^k(A) as a bar field over k and n."""
    cam = Camera(eye=(8.6, -8.2, 5.4), target=(1.9, 1.0, 0.45), focal=9.0,
                 scale=1.95)
    sc, P = Scene(cam), Placer()

    W, D, HS = 0.34, 0.40, 0.42
    cols = {2: "PIndigo", 3: "PTeal", 4: "PViolet"}
    for j, n in enumerate((2, 3, 4)):
        for k in range(0, 2 * n + 1):
            h = 3 if k == n else 1
            box(sc, k * 0.46, j * 0.62, 0.0, W, D, h * HS,
                cols[n] if k != n else "PAmber",
                op=0.92 if k == n else 0.80)

    sc.polyline([(-0.22, -0.18, 0), (4.15, -0.18, 0)],
                "PInk,line width=0.6pt,-{Stealth[length=3.6pt]}")
    sc.polyline([(-0.22, -0.18, 0), (-0.22, 1.82, 0)],
                "PInk,line width=0.6pt,-{Stealth[length=3.6pt]}")
    sc.polyline([(-0.22, -0.18, 0), (-0.22, -0.18, 1.55)],
                "PInk,line width=0.6pt,-{Stealth[length=3.6pt]}")

    P.add((4.15, -0.18, 0), r"$k$", side="R")
    P.add((-0.22, 1.82, 0), r"$n=2,3,4$", side="L")
    P.add((-0.22, -0.18, 1.55), r"$\dim_{\QQ}\Hdg^{k}(A)$", side="L")
    P.add((2 * 0.46, 0.62, 3 * HS), r"$k=n$: $\QQ\eta^{n}\oplus W(A)$",
          "text=PAmber", side="R")
    P.add((5 * 0.46, 1.24, HS), r"one class $\eta^{k}$ elsewhere",
          "text=PViolet", side="R")
    write("fig_hodgespike",
          "The dimensions of Hdg^k(A) over k and n: one everywhere except "
          "the middle degree, three there.",
          sc, P)


