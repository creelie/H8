def fig_charactergrid():
    """The summand at (r,s) of H^{2n}, with its true dimension as height."""
    cam = Camera(eye=(8.4, -8.6, 5.6), target=(1.5, 0.0, 0.55), focal=9.0,
                 scale=2.30)
    sc, P = Scene(cam), Placer()

    n = 3
    dims = [binom(2 * n, r) * binom(2 * n, 2 * n - r) for r in range(2 * n + 1)]
    top = max(dims)
    for r, d in enumerate(dims):
        h = 1.55 * (d / top) ** 0.55
        if r in (0, 2 * n):
            col = "PMag"
        elif r == n:
            col = "PAmber"
        else:
            col = "PIndigo"
        box(sc, r * 0.52, 0.0, 0.0, 0.38, 0.46, max(h, 0.05), col,
            op=0.90)

    sc.polyline([(-0.20, -0.16, 0), (3.50, -0.16, 0)],
                "PInk,line width=0.6pt,-{Stealth[length=3.6pt]}")
    sc.polyline([(-0.20, -0.16, 0), (-0.20, -0.16, 1.80)],
                "PInk,line width=0.6pt,-{Stealth[length=3.6pt]}")

    P.add((3.50, -0.16, 0), r"$r$, with $s=2n-r$", side="R")
    P.add((-0.20, -0.16, 1.80),
          r"$\dim\bigl(\bigwedge^{r}V_{+}\otimes\bigwedge^{s}V_{-}\bigr)$",
          side="L")
    P.add((0.0, 0.23, 0.30), r"$(2n,0)$ and $(0,2n)$: the Weil line",
          "text=PMag", side="L")
    P.add((n * 0.52, 0.23, 1.55), r"$(n,n)$: $\eta^{n}$ lives here",
          "text=PAmber", side="R")
    P.add((5 * 0.52, 0.23, 0.95), r"$\binom{6}{r}\binom{6}{6-r}$, summing to "
                                  r"$\binom{12}{6}=924$", "text=PIndigo",
          side="R")
    write("fig_charactergrid",
          "The K-grading of H^{2n} at n = 3: the summand at (r,s) with its "
          "true dimension, and the three cells that matter.",
          sc, P)


