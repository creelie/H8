PT = 2.54 / 72.27            # one TeX point in cm
BORDER = 8 * PT              # the standalone border
DPI = 127                    # 0.02 cm per pixel in the draft bitmaps
PX = 2.54 / DPI

HEAD = r"""%% {name}.tex   (generated by {gen}; do not edit by hand)
%% {blurb}
\documentclass[tikz,border=8pt]{{standalone}}
\usepackage{{amsmath,amssymb}}
\usetikzlibrary{{arrows.meta,calc}}
\input{{palette}}
\begin{{document}}
\begin{{tikzpicture}}[x=1cm,y=1cm,line join=round,line cap=round,
  font=\small,text=PInk]
"""
TAIL = "\\end{tikzpicture}\n\\end{document}\n"
TIP = "-{Stealth[length=4.2pt,width=3.4pt]}"

COORD = re.compile(r'\(\s*(-?\d+\.?\d*)\s*,\s*(-?\d+\.?\d*)\s*\)')
MEAS = re.compile(r'MEAS (\d+) (-?[\d.]+)pt (-?[\d.]+)pt (-?[\d.]+)pt')


def ink_bbox(body):
    xs, ys = [], []
    for a, b in COORD.findall(body):
        xs.append(float(a))
        ys.append(float(b))
    return min(xs), min(ys), max(xs), max(ys)


def soften(body):
    """Turn every stroke drawn with the style prefix 'soft,' into a path
    that a leader may cross (light rulings and hatching), and drop the
    prefix."""
    return re.sub(r'\\draw\[soft,([^,\]]+)', r'\\path[draw=\1', body)


def orbit_eye(target, dist, az, el):
    """An eye at distance dist from target, azimuth az and elevation el in
    degrees; a far eye with a long focal length is nearly orthographic."""
    a, e = math.radians(az), math.radians(el)
    return (target[0] + dist * math.cos(e) * math.cos(a),
            target[1] + dist * math.cos(e) * math.sin(a),
            target[2] + dist * math.sin(e))


def strokes_only(body):
    """The body without its shaded fills: what a leader may not cross."""
    keep = []
    for ln in body.splitlines(True):
        s = ln.lstrip()
        if s.startswith("\\path[") or s.startswith("\\fill["):
            continue
        keep.append(ln)
    return "".join(keep)


def _read_pgm(path):
    data = open(path, "rb").read()
    tok, i = [], 0
    while len(tok) < 4:
        while data[i:i + 1].isspace():
            i += 1
        if data[i:i + 1] == b"#":
            while data[i:i + 1] != b"\n":
                i += 1
            continue
        j = i
        while not data[j:j + 1].isspace():
            j += 1
        tok.append(data[i:j])
        i = j
    i += 1
    w, h = int(tok[1]), int(tok[2])
    return np.frombuffer(data[i:i + w * h], dtype=np.uint8).reshape(h, w)


def _seg_hits_box(p, q, b):
    """Does the segment pq meet the axis-parallel box b = (x0,y0,x1,y1)?"""
    x0, y0, x1, y1 = b
    t0, t1 = 0.0, 1.0
    dx, dy = q[0] - p[0], q[1] - p[1]
    for pp, qq in ((-dx, p[0] - x0), (dx, x1 - p[0]),
                   (-dy, p[1] - y0), (dy, y1 - p[1])):
        if abs(pp) < 1e-12:
            if qq < 0:
                return False
        else:
            t = qq / pp
            if pp < 0:
                t0 = max(t0, t)
            else:
                t1 = min(t1, t)
            if t0 > t1:
                return False
    return True


def _segs_cross(a, b, c, d):
    def orient(p, q, r):
        return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])
    o1, o2 = orient(a, b, c), orient(a, b, d)
    o3, o4 = orient(c, d, a), orient(c, d, b)
    return (o1 * o2 < 0) and (o3 * o4 < 0)


def _meet(a, b, pad=0.0):
    return (a[0] - pad < b[2] and b[0] - pad < a[2] and
            a[1] - pad < b[3] and b[1] - pad < a[3])


LOOSE = bool(os.environ.get("PLATE_LOOSE"))


def fail(msg):
    """A placement failure stops the build, unless PLATE_LOOSE is set, when
    it is reported and the plate is written anyway for inspection."""
    if LOOSE:
        print("  WARNING " + msg)
    else:
        raise SystemExit(msg)


class Plate:
    """A figure: TikZ geometry plus labels placed clear of it."""

    def __init__(self, name, gen, blurb, thresh=236, sthresh=246,
                 pad=0.05, gap=0.07):
        self.name, self.gen, self.blurb = name, gen, blurb
        self.parts = []
        self.fixed = []
        self.movable = []
        self.thresh = thresh      # grey level below which a pixel is ink
        self.sthresh = sthresh    # the same for the strokes a leader avoids
        self.pad = pad            # clear margin around a label box
        self.gap = gap            # minimum clearance between two labels

    # ------------------------------------------------------------ input
    def add(self, tikz):
        self.parts.append(tikz)

    def put(self, x, y, text, color="PInk", font=r"\small", extra="",
            anchor="c"):
        """A label at a fixed position; anchor is one of c, w, e, n, s and
        says which point of the box is at (x, y)."""
        self.fixed.append(dict(x=x, y=y, text=text, color=color, font=font,
                               extra=extra, anchor=anchor))

    def label(self, at, text, color="PInk", font=r"\small", dirs=None,
              rmin=0.04, rmax=3.5, lead=0.26, skip=0.10, frame=None,
              penalty=0.9):
        """A label near the point `at`; dirs lists preferred directions in
        degrees (0 = east, 90 = north)."""
        self.movable.append(dict(ax=at[0], ay=at[1], text=text, color=color,
                                 font=font, dirs=dirs, rmin=rmin, rmax=rmax,
                                 lead=lead, skip=skip, frame=frame,
                                 penalty=penalty, extra=""))

    # ---------------------------------------------------------- helpers
    @staticmethod
    def _spec(it):
        ex = ",align=center" if "\\\\" in it["text"] else ""
        return "text=%s,font=%s,inner sep=0pt%s%s" % (
            it["color"], it["font"], ex,
            ("," + it["extra"]) if it["extra"] else "")

    @staticmethod
    def _node(it, x, y):
        return "  \\node[%s] at (%.3f,%.3f) {%s};\n" % (Plate._spec(it), x, y,
                                                        it["text"])

    def _compile(self, tex, tmp, stem):
        with open(os.path.join(tmp, stem + ".tex"), "w") as f:
            f.write(tex)
        r = subprocess.run(["pdflatex", "-interaction=nonstopmode",
                            "-halt-on-error", stem + ".tex"], cwd=tmp,
                           capture_output=True, text=True)
        if r.returncode != 0:
            sys.stdout.write(r.stdout[-3000:])
            raise SystemExit("pdflatex failed on the draft of %s" % self.name)
        return r.stdout

    def _render(self, tmp, stem):
        subprocess.run(["pdftoppm", "-gray", "-r", str(DPI), "-singlefile",
                        stem + ".pdf", stem], cwd=tmp, check=True)
        return _read_pgm(os.path.join(tmp, stem + ".pgm"))

    # ------------------------------------------------------------ build
    def build(self):
        body = "".join(self.parts)
        bx0, by0, bx1, by1 = ink_bbox(body)
        M = 5.0
        X0, Y0, X1, Y1 = bx0 - M, by0 - M, bx1 + M, by1 + M
        ubox = "  \\useasboundingbox (%.3f,%.3f) rectangle (%.3f,%.3f);\n" % (
            X0, Y0, X1, Y1)
        items = self.fixed + self.movable
        meas = []
        for i, it in enumerate(items):
            t = it["text"]
            if "\\\\" in t:
                t = "\\begin{tabular}{@{}c@{}}%s\\end{tabular}" % t
            meas.append("  \\pgfinterruptpicture\\setbox0\\hbox{%s %s}"
                        "\\typeout{MEAS %d \\the\\wd0 \\space\\the\\ht0 "
                        "\\space\\the\\dp0 }\\endpgfinterruptpicture\n"
                        % (it["font"], t, i))
        head = HEAD.format(name=self.name, gen=self.gen, blurb=self.blurb)
        tmp = tempfile.mkdtemp(prefix="plate_")
        try:
            shutil.copy(os.path.join(HERE, "palette.tex"), tmp)
            log = self._compile(head + ubox + body + "".join(meas) + TAIL,
                                tmp, "draft")
            sizes = {}
            for m in MEAS.finditer(log):
                i = int(m.group(1))
                w = float(m.group(2)) * PT
                h = (float(m.group(3)) + float(m.group(4))) * PT
                sizes[i] = (w, h)
            for i, it in enumerate(items):
                w, h = sizes[i]
                if "rotate=90" in it["extra"]:
                    w, h = h, w
                it["w"], it["h"] = w, h
                a = it.get("anchor", "c")
                it["x"] = it.get("x", 0) + {"w": w / 2, "e": -w / 2}.get(a, 0)
                it["y"] = it.get("y", 0) + {"s": h / 2, "n": -h / 2}.get(a, 0)
            full = self._render(tmp, "draft")
            self._compile(head + ubox + strokes_only(body) + TAIL, tmp,
                          "strokes")
            strk = self._render(tmp, "strokes")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

        H, W = full.shape
        ink = (full < self.thresh).astype(np.int32)
        S = np.zeros((H + 1, W + 1), dtype=np.int64)
        S[1:, 1:] = ink.cumsum(0).cumsum(1)
        sink = strk < self.sthresh
        ox, oy = X0 - BORDER, Y1 + BORDER

        def box_ink(b):
            c0 = int(math.floor((b[0] - ox) / PX))
            c1 = int(math.ceil((b[2] - ox) / PX))
            r0 = int(math.floor((oy - b[3]) / PX))
            r1 = int(math.ceil((oy - b[1]) / PX))
            if c0 < 0 or r0 < 0 or c1 > W or r1 > H:
                return 10 ** 6
            return int(S[r1, c1] - S[r0, c1] - S[r1, c0] + S[r0, c0])

        def pix_stroke(x, y):
            c = int((x - ox) / PX)
            r = int((oy - y) / PX)
            if c < 1 or r < 1 or c >= W - 1 or r >= H - 1:
                return True
            return bool(sink[r - 1:r + 2, c - 1:c + 2].any())

        placed = []        # (real box, cf box, text)
        leaders = []       # (p, q)
        pad, gap = self.pad, self.gap

        def clear_of_labels(rb, cb):
            for (pb, pc, _) in placed:
                if _meet(rb, pb, gap) or _meet(cb, pc, 0.0):
                    return False
            return True

        # the fixed labels first: they must be clear as given
        for it in self.fixed:
            x, y, w, h = it["x"], it["y"], it["w"], it["h"]
            rb = (x - w / 2, y - h / 2, x + w / 2, y + h / 2)
            cb = cf_box(self._spec(it), x, y, it["text"])[:4]
            n = box_ink((rb[0] - pad, rb[1] - pad, rb[2] + pad, rb[3] + pad))
            if n:
                fail("%s: fixed label %r meets the ink (%d px)"
                     % (self.name, it["text"], n))
            if not clear_of_labels(rb, cb):
                fail("%s: fixed label %r meets another label"
                     % (self.name, it["text"]))
            placed.append((rb, cb, it["text"]))

        out_lead, out_node = [], []
        for it in self.fixed:
            out_node.append(self._node(it, it["x"], it["y"]))

        for it in self.movable:
            ax, ay, w, h = it["ax"], it["ay"], it["w"], it["h"]
            cands = []
            pref = it["dirs"]
            for k in range(32):
                th = 11.25 * k
                if pref is None:
                    pen = 0.15 * abs(math.sin(math.radians(th)))
                else:
                    dd = min(min(abs(th - p) % 360, 360 - abs(th - p) % 360)
                             for p in pref)
                    pen = 0.0 if dd < 1e-6 else it["penalty"] * (0.5 + dd / 180.0)
                ux, uy = math.cos(math.radians(th)), math.sin(math.radians(th))
                s = abs(ux) * w / 2 + abs(uy) * h / 2
                r = it["rmin"]
                while r <= it["rmax"] + 1e-9:
                    cands.append((r + pen, r, ux, uy, s))
                    r += 0.03
            cands.sort()
            done = False
            for score, r, ux, uy, s in cands:
                cx, cy = ax + (r + s) * ux, ay + (r + s) * uy
                rb = (cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2)
                fr = it["frame"]
                if fr and (rb[0] < fr[0] or rb[1] < fr[1] or rb[2] > fr[2]
                           or rb[3] > fr[3]):
                    continue
                if box_ink((rb[0] - pad, rb[1] - pad, rb[2] + pad,
                            rb[3] + pad)):
                    continue
                cb = cf_box(self._spec(it), cx, cy, it["text"])[:4]
                if not clear_of_labels(rb, cb):
                    continue
                grown = (rb[0] - pad, rb[1] - pad, rb[2] + pad, rb[3] + pad)
                if any(_seg_hits_box(p, q, grown) for p, q in leaders):
                    continue
                seg = None
                if r > it["lead"]:
                    # exit point of the ray from the centre towards the anchor
                    tx = (w / 2 + 0.05) / abs(ux) if abs(ux) > 1e-9 else 1e9
                    ty = (h / 2 + 0.05) / abs(uy) if abs(uy) > 1e-9 else 1e9
                    te = min(tx, ty)
                    B = (cx - te * ux, cy - te * uy)
                    A = (ax + 0.05 * ux, ay + 0.05 * uy)
                    L = math.hypot(B[0] - A[0], B[1] - A[1])
                    ok = L > 0.05
                    n = max(2, int(L / 0.015))
                    for q in range(n + 1):
                        t = q / n
                        x = A[0] + (B[0] - A[0]) * t
                        y = A[1] + (B[1] - A[1]) * t
                        if math.hypot(x - ax, y - ay) < it["skip"]:
                            continue
                        if pix_stroke(x, y):
                            ok = False
                            break
                    if not ok:
                        continue
                    if any(_seg_hits_box(A, B, (pb[0] - pad, pb[1] - pad,
                                                pb[2] + pad, pb[3] + pad))
                           for (pb, _, _) in placed):
                        continue
                    if any(_segs_cross(A, B, p, q) for p, q in leaders):
                        continue
                    seg = (A, B)
                placed.append((rb, cb, it["text"]))
                if seg:
                    leaders.append(seg)
                    out_lead.append("  \\draw[PSlate!60,line width=0.3pt] "
                                    "(%.3f,%.3f) -- (%.3f,%.3f);\n"
                                    % (seg[0][0], seg[0][1], seg[1][0],
                                       seg[1][1]))
                out_node.append(self._node(it, cx, cy))
                done = True
                break
            if not done:
                fail("%s: no clear position for label %r"
                     % (self.name, it["text"]))

        # the checkfigs estimate, over every text node of the plate
        cfs = [p[1] for p in placed]
        for i, a in enumerate(cfs):
            for b in cfs[i + 1:]:
                if _meet(a, b):
                    fail("%s: checkfigs boxes meet" % self.name)

        tex = head + body + "".join(out_lead) + "".join(out_node) + TAIL
        path = os.path.join(HERE, self.name + ".tex")
        with open(path, "w") as f:
            f.write(tex)
        allx = [p[0][0] for p in placed] + [p[0][2] for p in placed] + [bx0, bx1]
        ally = [p[0][1] for p in placed] + [p[0][3] for p in placed] + [by0, by1]
        print("%-16s %2d labels (%d with leaders), about %.1f x %.1f cm"
              % (self.name, len(placed), len(leaders),
                 max(allx) - min(allx), max(ally) - min(ally)))
        return tex


def compile_plate(name):
    """pdflatex, the 200 dpi PNG, and the cleanup, in the figures folder."""
    r = subprocess.run(["pdflatex", "-interaction=nonstopmode",
                        "-halt-on-error", name + ".tex"], cwd=HERE,
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.stdout.write(r.stdout[-3000:])
        raise SystemExit("pdflatex failed on %s" % name)
    subprocess.run(["pdftoppm", "-png", "-r", "200", "-singlefile",
                    name + ".pdf", name], cwd=HERE, check=True)
    for ext in (".aux", ".log"):
        try:
            os.remove(os.path.join(HERE, name + ext))
        except OSError:
            pass


