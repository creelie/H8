def fig_signature():
    tgt = (1.85, 1.85, 1.05)
    cam = Camera(eye=orbit_eye(tgt, 34.0, -112.0, 21.0), target=tgt,
                 focal=34.0, scale=2.0)
    sc = Scene(cam)
    pl = Plate("fig_signature", "make_diagrams.py",
               "The signatures (p,q) of an imaginary quadratic action on the "
               "saddle z = pq, with the Weil ridge p = q.")
    S = 0.36          # lattice spacing
    Hs = 0.068        # height per unit of pq
    N = 12

    def pt(p, q, z=None):
        return (p * S, q * S, (p * q if z is None else z) * Hs)

    # the saddle z = pq over the triangle p, q >= 0, p + q <= 12
    sc.surface(lambda s, lam: pt(lam * s, (1 - lam) * s), (0.0, float(N)),
               (0.0, 1.0), 24, 24, base="PSlate", opacity=0.20,
               ambient=0.66, diffuse=0.30)
    for a, b in (((0, 0), (N + 1.3, 0)), ((0, 0), (0, N + 1.3))):
        sc.polyline([pt(a[0], a[1], 0), pt(b[0], b[1], 0)],
                    "PSlate,line width=0.5pt," + TIP, priority=1)
    for i in range(0, N + 1, 2):
        sc.polyline([pt(i, 0, 0), pt(i, -0.35, 0)],
                    "PSlate,line width=0.4pt", priority=1)
    # the curves p + q = 2n on the saddle, with their signatures
    for m in range(1, 7):
        s = 2 * m
        sc.curve(lambda t, s=s: pt(t, s - t), (0.0, float(s)), 14 * m,
                 "PInk!75,line width=0.6pt", priority=2, chunk=2)
        for p in range(0, s + 1):
            if p != s - p:
                sc.dot3(pt(p, s - p), "circle,draw=PInk!80,fill=white,"
                        "line width=0.45pt,inner sep=1.05pt", priority=5)
    # the ridge p = q, where the Weil line consists of Hodge classes
    sc.curve(lambda t: pt(t, t), (0.0, 6.0), 60, "PClay,line width=1.5pt",
             priority=4, chunk=2)
    sc.polyline([pt(0, 0, 0), pt(6, 6, 0)],
                "PClay!60,line width=0.5pt,dash pattern=on 2pt off 1.5pt",
                priority=2)
    for n in range(1, 7):
        sc.polyline([pt(n, n, 0), pt(n, n)],
                    "PClay!60,line width=0.4pt,dash pattern=on 1pt off 1.2pt",
                    priority=3)
        sc.dot3(pt(n, n), "circle,fill=PClay,draw=white,line width=0.6pt,"
                "inner sep=1.9pt", priority=6)
    pl.add(sc.emit())

    for i in range(2, N + 1, 2):
        x, y = proj(cam, pt(i, -0.35, 0))
        pl.put(x + 0.05, y - 0.20, r"$%d$" % i, color="PSlate",
               font=r"\footnotesize")
    for n in range(1, 7):
        pl.label(proj(cam, pt(n, n)), r"$%d$" % (n * n), color="PClay",
                 font=r"\footnotesize", dirs=[180, 160, 200], rmax=1.0,
                 lead=0.5)
    pl.label(proj(cam, pt(N + 1.3, 0, 0)), r"$p$", color="PSlate",
             dirs=[0, 30], rmax=0.4)
    pl.label(proj(cam, pt(0, N + 1.3, 0)), r"$q$", color="PSlate",
             dirs=[180, 150], rmax=0.4)
    for m in range(1, 7):
        pl.label(proj(cam, pt(0, 2 * m)), r"$p+q=%d$" % (2 * m),
                 color="PInk", font=r"\footnotesize", dirs=[180, 200, 160],
                 rmin=0.12, rmax=0.8, lead=0.3)
    pl.build()
    compile_plate("fig_signature")


