def fig_fibres():
    """The null cone, the two conjugate isotropic planes, and the fibres."""
    cam = Camera(eye=(6.4, -8.0, 4.5), target=(0, 0, 0.10), focal=8.2,
                 scale=2.45)
    sc, P = Scene(cam), Placer()

    for sgn in (1, -1):
        sc.surface(lambda u, v, s=sgn: (v * math.cos(u), v * math.sin(u),
                                        s * v),
                   (0, 2 * math.pi), (0.05, 2.30), 90, 16,
                   base="PSlate", opacity=0.26, ambient=0.54, diffuse=0.38)
        # rulings of the cone, so it reads as a ruled surface and not a blob
        for k in range(24):
            t = 2 * math.pi * k / 24.0
            sc.curve(lambda s, t=t, sg=sgn: (s * math.cos(t), s * math.sin(t),
                                             sg * s),
                     (0.05, 2.30), 10,
                     "PSlate,line width=0.32pt,opacity=0.55", chunk=3)

    for v in ((2.45, 0, 0), (0, 2.45, 0), (0, 0, 2.55)):
        sc.polyline([(0, 0, 0), v],
                    "PSlate,line width=0.45pt,opacity=0.7,"
                    "-{Stealth[length=3.4pt]}")

    sc.surface(lambda u, v: (u, v, u + v), (-1.5, 1.5), (-1.5, 1.5), 24, 24,
               base="PIndigo", opacity=0.50, ambient=0.44, diffuse=0.56)
    sc.surface(lambda u, v: (u, -v, u - v), (-1.5, 1.5), (-1.5, 1.5), 24, 24,
               base="PMag", opacity=0.50, ambient=0.44, diffuse=0.56)

    for k in range(-4, 5):
        t = 0.34 * k
        a, b = (t, t, 2 * t), (t, -t, 0.0)
        sc.polyline([a, b], "PGrass,line width=1.05pt")
        sc.dot3(a, "circle,fill=PIndigo,draw=white,line width=0.45pt,"
                   "inner sep=1.25pt")
        sc.dot3(b, "circle,fill=PMag,draw=white,line width=0.45pt,"
                   "inner sep=1.25pt")

    sc.surface(lambda u, v: (u, u * (1 - 2 * v), 2 * u * (1 - v)),
               (-1.30, 1.30), (0.0, 1.0), 24, 12,
               base="PAmber", opacity=0.54, ambient=0.50, diffuse=0.46)

    P.add((1.42, 1.42, 2.84), r"$V_{+}$", "text=PIndigo", side="R")
    P.add((1.42, -1.42, 0.0), r"$V_{-}$", "text=PMag", side="R")
    P.add((0.30, -0.30, 0.90), r"$V_{+}^{0,1}\otimes V_{-}^{0,1}$",
          "text=PAmber", side="L")
    P.add((1.62, 0.0, 1.62), r"$q=x^{2}+y^{2}-z^{2}=0$", "text=PSlate", side="R")
    P.add((-1.20, -1.20, 0.0), r"fibres", "text=PGrass", side="L")
    write("fig_fibres",
          "The null cone with its rulings, the two conjugate isotropic "
          "planes, the fibres joining them, and the mixed block.",
          sc, P)


if __name__ == "__main__":
    fig_quadric()
    fig_lagsweep()
    fig_fibres()
    print("three plates written")
