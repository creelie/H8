def fig_lagsweep():
    """A pencil of planes through a common line: the fan of Lagrangians."""
    cam = Camera(eye=(5.0, -7.6, 4.6), target=(0, 0, 0.0), focal=8.6,
                 scale=2.30)
    sc, P = Scene(cam), Placer()

    R = 1.55
    axis = (1.0, 0.0, 0.0)
    fan = [(-1.16, "PSlate", 0.20, False), (-0.92, "PIndigo", 0.22, False),
           (-0.64, "PViolet", 0.24, False), (-0.36, "PTeal", 0.38, True),
           (-0.12, "PBlue", 0.22, False), (0.12, "PGrass", 0.22, False),
           (0.36, "PAmber", 0.38, True), (0.64, "PClay", 0.24, False),
           (0.92, "PMag", 0.22, False), (1.16, "PSlate", 0.20, False)]
    for th, col, op, rational in fan:
        e2 = (0.0, math.cos(th), math.sin(th))

        def plane(u, v, e2=e2):
            return addv(smul(R * v * math.cos(u), axis),
                        smul(R * v * math.sin(u), e2))
        sc.surface(plane, (0, 2 * math.pi), (0.05, 1.0), 60, 8,
                   base=col, opacity=op, ambient=0.48, diffuse=0.48)
        sc.curve(lambda u, e2=e2: addv(smul(R * math.cos(u), axis),
                                       smul(R * math.sin(u), e2)),
                 (0, 2 * math.pi), 96,
                 "%s,line width=%.2fpt" % (col, 1.15 if rational else 0.55),
                 chunk=2)

    sc.polyline([(-R * 1.16, 0, 0), (R * 1.16, 0, 0)],
                "PInk,line width=1.0pt")
    sc.dot3((0, 0, 0), "circle,fill=PInk,inner sep=1.5pt,draw=none")

    P.add((0.0, R * math.cos(-0.36), R * math.sin(-0.36)),
          r"$\psi\in\End^{0}(A)$", "text=PTeal", side="L")
    P.add((0.0, R * math.cos(0.36), R * math.sin(0.36)),
          r"$\psi'\in\End^{0}(A)$", "text=PAmber", side="R")
    P.add((0.0, R * math.cos(1.16), R * math.sin(1.16)),
          r"$\psi$ real: the fan is a continuum", "text=PSlate", side="R")
    P.add((0.0, R * math.cos(-1.16), R * math.sin(-1.16)),
          r"each leaf is an $\mathrm{LG}(n,2n)$", "text=PViolet", side="L")
    P.add((R * 1.16, 0, 0), r"the common axis", side="R")
    write("fig_lagsweep",
          "The fan of Lagrangian loci: each psi gives one leaf, the real psi "
          "sweep the family, the rational psi pick out countably many.",
          sc, P)


